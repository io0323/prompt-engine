package promptengine.domain.execution

/**
 * [ExecutionAdapter.execute]が失敗した際のエラー分類（設計書§2.6ステージ9、ADR-0014決定2・決定7）。
 *
 * プロバイダ固有の概念（HTTPステータスコード等）を直接表現せず、リトライ可否の判断に
 * 必要な抽象度でのみ分類する（CLAUDE.md「特定のAIプロバイダ名・モデル名をコードに直接書かない」）。
 *
 * [CONNECT_TIMEOUT]と[READ_TIMEOUT]を分けるのは、両者でリトライの安全性が全く異なるため
 * （ADR-0014決定7）: [CONNECT_TIMEOUT]は接続確立前のタイムアウトであり、リクエストが
 * 先方に到達していないと断定できる。[READ_TIMEOUT]は応答待機中のタイムアウトであり、
 * 先方で既に実行（課金を伴う可能性がある）が完了している可能性を否定できないため、
 * 単純にリトライすると二重実行のリスクがある。
 */
enum class ExecutionErrorType {
    /** 接続確立前のタイムアウト。未送信と断定できる（リトライ可）。 */
    CONNECT_TIMEOUT,

    /** 応答待機中のタイムアウト。先方で実行済み・課金済みの可能性を否定できない（リトライ不可）。 */
    READ_TIMEOUT,

    /** 接続自体が確立できなかった。未送信と断定できる（リトライ可）。 */
    CONNECTION_FAILURE,

    /** レート制限（429相当）。実行前に拒否された（リトライ可）。 */
    RATE_LIMITED,

    /** サーバエラー（5xx相当）。プロバイダ側が明示的に失敗を返した（リトライ可）。 */
    SERVER_ERROR,

    /** クライアントエラー（429を除く4xx相当）。再送しても結果は変わらない（リトライ不可）。 */
    CLIENT_ERROR,

    /** 分類不能。安全側に倒しリトライ不可として扱う。 */
    UNKNOWN,
}
